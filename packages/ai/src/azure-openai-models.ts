import type { ModelInfo } from "./model.ts";

const defaults = {
  providerId: "azure-openai",
  apiDialect: "openai-responses",
  capabilities: { toolUse: true, structuredOutput: true, imageInput: true },
} as const;

interface AzureModelDefinition {
  readonly modelId: string;
  readonly displayName: string;
  readonly reasoning: boolean;
  readonly contextWindow: number;
  readonly maxOutputTokens: number;
  readonly input: number;
  readonly output: number;
  readonly cacheRead?: number;
  readonly cacheWrite?: number;
  readonly imageInput?: boolean;
  readonly thinkingLevelMap?: ModelInfo["thinkingLevelMap"];
  readonly grammarTools?: boolean;
}

function azureModel(definition: AzureModelDefinition): ModelInfo {
  return {
    ...defaults,
    modelId: definition.modelId,
    displayName: definition.displayName,
    reasoning: definition.reasoning,
    capabilities: {
      ...defaults.capabilities,
      imageInput: definition.imageInput ?? true,
    },
    contextWindow: definition.contextWindow,
    maxOutputTokens: definition.maxOutputTokens,
    cost: {
      inputUsdPerMTok: definition.input,
      outputUsdPerMTok: definition.output,
      cacheReadUsdPerMTok: definition.cacheRead ?? 0,
      cacheWriteUsdPerMTok: definition.cacheWrite ?? 0,
    },
    ...(definition.thinkingLevelMap === undefined
      ? {}
      : { thinkingLevelMap: definition.thinkingLevelMap }),
    ...(definition.grammarTools ? { compatibility: { supportsOpenAIGrammarTools: true } } : {}),
  };
}

